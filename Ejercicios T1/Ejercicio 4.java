public class Traduccion {
    public static void main(String[] args) {
        System.out.println("English\t\tCastellano");
        System.out.println("--------\t\t---------");
        System.out.println("Hello\t\tHola");
        System.out.println("Goodbye\t\tAdiós");
        System.out.println("House\t\tCasa");
        System.out.println("Dog\t\tPerro");
        System.out.println("Cat\t\tGato");
        System.out.println("Book\t\tLibro");
        System.out.println("Car\t\tCoche");
        System.out.println("Water\t\tAgua");
        System.out.println("Food\t\tComida");
        System.out.println("School\t\tEscuela");
    }
}
